package codegen

import (
	"context"

	gs "github.com/longxi-go/gosr/pkg/ioc"
	"github.com/longxi-go/ioc/internal/compiler"
	http "github.com/longxi-go/ioc/pkg/codegen/http"
)

// Options selects an owned module, application entry and explicit source roots.
// Nonempty Tags override GOFLAGS -tags; target settings and enabled instrumentation
// still apply. Check verifies exact generated bytes without modifying source.
// Library publishes metadata for consumers.
type Options struct {
	Dir, Entry     string
	Library, Check bool
	Tags, Roots    []string
	// HTTP explicitly selects transport generation; nil rejects HTTP endpoints.
	HTTP http.Adapter
}

// Edge reports a declared potential dependency relationship. From
// requires To; Kind distinguishes injected dependencies from named initialization
// prerequisites. Deferred access does not create an immediate creation edge.
// Source identifies the declaration; runtime conditions may exclude candidates.
type Edge struct {
	From, To string
	Kind     EdgeKind
	Source   gs.Source
	Access   gs.Access
}

// Report owns detached definitions, deterministic output paths and diagnostics.
type Report struct {
	Definitions        []gs.BeanDefinition
	Files, Diagnostics []string
	Edges              []Edge
}

// Run validates the complete input and generated closure before publishing any
// output. Canceled compilation does not execute factories or mutate dependencies.
func Run(ctx context.Context, options Options) (*Report, error) {
	return run(ctx, options, false)
}

// Inspect analyzes and type-checks prospective output without writing files. It
// supports read-only explain/graph tools even before the first generation.
func Inspect(ctx context.Context, options Options) (*Report, error) {
	return run(ctx, options, true)
}

func run(ctx context.Context, o Options, inspect bool) (*Report, error) {
	result, err := compiler.Run(ctx, compiler.Options{
		Dir:     o.Dir,
		HTTP:    o.HTTP,
		Entry:   o.Entry,
		Library: o.Library,
		Check:   o.Check,
		Inspect: inspect,
		Tags:    o.Tags,
		Roots:   o.Roots,
	})
	if result == nil {
		return nil, err
	}
	report := &Report{
		Definitions: result.Definitions,
		Files:       result.Files,
		Diagnostics: result.Diagnostics,
	}
	for _, edge := range result.Edges {
		report.Edges = append(report.Edges, Edge{
			From:   edge.From,
			To:     edge.To,
			Access: edge.Access,
			Kind:   EdgeKind(edge.Kind),
			Source: edge.Source,
		})
	}
	return report, err
}

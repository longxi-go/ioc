package compiler

import (
	"go/types"

	gs "github.com/longxi-go/gosr/pkg/ioc"
	"github.com/longxi-go/ioc/pkg/bean"
	http "github.com/longxi-go/ioc/pkg/codegen/http"
)

const (
	runtimeModule    = "github.com/longxi-go/ioc"
	contractsModule  = "github.com/longxi-go/gosr"
	contractsPackage = contractsModule + "/pkg/ioc"
	eventPackage     = "github.com/longxi-go/gosr/pkg/event"
	generatedHeader  = "// Code generated by ioc. DO NOT EDIT.\n"
	schema           = 5
)

// Options is private to the compiler boundary; pkg/codegen owns the public API.
type Options struct {
	Dir, Entry              string
	Library, Check, Inspect bool
	Tags, Roots             []string
	HTTP                    http.Adapter
	isolated                bool
}

// Report is the detached result used by the public facade and command runner.
type Report struct {
	Definitions []gs.BeanDefinition
	Files       []string
	Diagnostics []string
	Edges       []Edge
}

// Edge records a declared potential dependency, including deferred access.
type Edge struct {
	From, To string
	Kind     EdgeKind
	Source   gs.Source
	Access   gs.Access
}

type typeSpec struct {
	Code    string
	Imports map[string]string
	Hidden  []string
}

type shape struct {
	Kind dependencyKind
	Type types.Type
	Elem *shape
}

type argument struct {
	Shape   *shape
	Field   string
	Context bool
	Port    int
}

type recipe struct {
	Definition   gs.BeanDefinition
	Package      string
	Function     string
	Component    string
	Result       types.Type
	Error        bool
	Args         []argument
	Exposed      []types.Type
	Conditions   []condition
	Hooks        []lifecycleHook
	ListenerType bool
	Listeners    []listener
}

type listener struct {
	Method, ID string
	Event      types.Type
	Source     gs.Source
	Order      *int
	Lifecycle  bool
}

type condition = bean.Condition

type packageModel struct {
	Path, Name, Dir string
	Recipes         []*recipe
	Pkg             *types.Package
	Sources         map[string]string
	Constraint      string
	HTTP            http.Package
}
